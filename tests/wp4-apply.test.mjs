import assert from 'node:assert/strict';
import fs from 'node:fs';import os from 'node:os';import path from 'node:path';import crypto from 'node:crypto';import {pathToFileURL} from 'node:url';
const repo=path.resolve(process.argv[2]||'.');
const load=name=>import(pathToFileURL(path.join(repo,name)).href);
const temp=prefix=>fs.realpathSync(fs.mkdtempSync(path.join(repo,'tests','tmp',prefix)));
const core=await load('delegation-core.mjs');
const tmp=temp('wp4-'),home=path.join(tmp,'home'),project=path.join(tmp,'project');fs.mkdirSync(path.join(project,'src'),{recursive:true});
fs.writeFileSync(path.join(project,'src','a.ts'),'one\r\ntwo\r\n');
const id=crypto.randomUUID(),dir=path.join(home,'delegations',id,'1');fs.mkdirSync(path.join(dir,'proposals','src'),{recursive:true});fs.mkdirSync(path.join(dir,'proposals','docs'),{recursive:true});
fs.writeFileSync(path.join(dir,'proposals','src','a.ts'),'one\nTWO\n');fs.writeFileSync(path.join(dir,'proposals','docs','n.md'),'# N\n');
fs.writeFileSync(path.join(home,'delegations',id,'batch.json'),JSON.stringify({id,project,tasks:[{title:'t',directory:dir,writeFiles:['src/a.ts','docs/n.md'],baseHashes:{'src/a.ts':crypto.createHash('sha256').update('one\r\ntwo\r\n').digest('hex'),'docs/n.md':null},state:'completed'}]}));
const res=core.applyProposals(home,{batch:id,task:1});
assert.equal(fs.readFileSync(path.join(project,'src','a.ts'),'utf8'),'one\r\nTWO\r\n');
assert.equal(fs.readFileSync(path.join(project,'docs','n.md'),'utf8'),'# N\n');
assert.deepEqual(res.applied.map(a=>a.path).sort(),['docs/n.md','src/a.ts']);
assert.throws(()=>core.applyProposals(home,{batch:id,task:1,files:['other.ts']}),/non assegnato/);
assert.throws(()=>core.applyProposals(home,{batch:'x',task:1}),/batch non valido/);
assert.throws(()=>core.applyProposals(home,{batch:id,task:2}),/inesistente/);
assert.deepEqual(JSON.parse(fs.readFileSync(path.join(home,'delegations',id,'batch.json'),'utf8')).tasks[0].applied.sort(),['docs/n.md','src/a.ts']);
console.log('WP4 OK');
assert.throws(()=>core.applyProposals(home,{batch:id,task:1},home),/altro progetto/);
core.applyProposals(home,{batch:id,task:1},project); // ripetizione idempotente sulla versione applicata
fs.writeFileSync(path.join(dir,'proposals','docs','n.md'),'# Changed\n');
assert.throws(()=>core.applyProposals(home,{batch:id,task:1,files:['docs/n.md','other.ts']},project),/non assegnato/);
assert.equal(fs.readFileSync(path.join(project,'docs','n.md'),'utf8'),'# N\n');
fs.writeFileSync(path.join(project,'src','a.ts'),'modifica utente');
assert.throws(()=>core.applyProposals(home,{batch:id,task:1},project),/File cambiato/);
assert.equal(fs.readFileSync(path.join(project,'src','a.ts'),'utf8'),'modifica utente');
assert.equal(fs.readFileSync(path.join(project,'docs','n.md'),'utf8'),'# N\n');
